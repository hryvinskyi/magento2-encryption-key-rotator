<?php

declare(strict_types=1);

namespace Hryvinskyi\EncryptionKeyRotator\Tests\Compatibility;

use Hryvinskyi\EncryptionKeyRotator\Domain\Crypto\Ciphertext;
use Hryvinskyi\EncryptionKeyRotator\Domain\Key\Key;
use Hryvinskyi\EncryptionKeyRotator\Domain\Key\KeyRing;
use Hryvinskyi\EncryptionKeyRotator\Tests\Support\CryptoServices;
use Hryvinskyi\EncryptionKeyRotator\Tests\Support\KeyMaterial;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Process\Process;

/**
 * Holds the tool to the store's own Encryptor, run from the code base MAGENTO_ROOT names with the PHP
 * MAGENTO_PHP names (default `php`): the two read each other's ciphertexts, and the store reads every
 * ring the tool writes the way the tool means it.
 *
 * The ring starts in a common shape after an earlier rotation: slot 0 retired, slot 1 a 32-character
 * key. Every key is generated by the test. The tool's side is built by the real container.
 */
final class MagentoEncryptorCompatibilityTest extends TestCase
{
    private const SCRIPT = __DIR__ . '/bin/magento-encryptor.php';

    private CryptoServices $services;
    private KeyRing $ring;

    protected function setUp(): void
    {
        $this->services = CryptoServices::shared();
        $this->ring = $this->services->ringParser()->parse(
            $this->services->keyGenerator()->placeholder() . "\n" . KeyMaterial::rawKey(),
        );
    }

    public function testTheStoreDecryptsWhatTheToolEncrypts(): void
    {
        $plaintexts = $this->plaintextsWithoutSurroundingWhitespace();
        $operations = [];
        foreach ($plaintexts as $plaintext) {
            $ciphertext = $this->encryptWithTool($plaintext, $this->ring);
            self::assertSame(1, $ciphertext->keyIndex());
            $operations[] = ['op' => 'decrypt', 'value' => $ciphertext->toString()];
        }

        $results = $this->runStore($this->ring->export(), $operations);

        foreach ($plaintexts as $position => $plaintext) {
            self::assertSame($plaintext, $this->decodedPlaintext($results[$position]), sprintf('Plaintext #%d', $position));
        }
    }

    public function testTheToolDecryptsWhatTheStoreEncrypts(): void
    {
        $plaintexts = $this->plaintextsWithoutSurroundingWhitespace();
        $plaintexts[] = "  surrounding whitespace survives the store's encryption\n";
        $operations = array_map(
            static fn(string $plaintext): array => ['op' => 'encrypt', 'plaintext' => base64_encode($plaintext)],
            $plaintexts,
        );

        $results = $this->runStore($this->ring->export(), $operations);

        $activeKey = $this->ring->active($this->services->keys());
        foreach ($plaintexts as $position => $plaintext) {
            $stored = $this->stringResult($results[$position], 'ciphertext');
            $ciphertext = $this->services->ciphertextParser()->parse($stored);
            self::assertNotNull($ciphertext, 'The parser accepts what the store writes.');
            self::assertSame($stored, $ciphertext->toString(), 'The parser gives the stored value back byte for byte.');
            self::assertSame(1, $ciphertext->keyIndex());
            self::assertSame(3, $ciphertext->cipherVersion());
            self::assertSame($plaintext, $this->services->cipher()->decrypt($ciphertext, $activeKey)?->bytes());
        }
    }

    public function testTheStoreSealsWithTheNonceAsAssociatedData(): void
    {
        $results = $this->runStore($this->ring->export(), [['op' => 'encrypt', 'plaintext' => base64_encode('associated data check')]]);

        $ciphertext = $this->services->ciphertextParser()->parse($this->stringResult($results[0], 'ciphertext'));
        self::assertNotNull($ciphertext);
        $payload = $ciphertext->payloadBytes();
        $nonce = substr($payload, 0, SODIUM_CRYPTO_AEAD_CHACHA20POLY1305_IETF_NPUBBYTES);
        $sealed = substr($payload, SODIUM_CRYPTO_AEAD_CHACHA20POLY1305_IETF_NPUBBYTES);
        $key = $this->ring->active($this->services->keys())->bytes();
        self::assertSame('associated data check', sodium_crypto_aead_chacha20poly1305_ietf_decrypt($sealed, $nonce, $nonce, $key));
        self::assertFalse(sodium_crypto_aead_chacha20poly1305_ietf_decrypt($sealed, '', $nonce, $key));
    }

    public function testTheStoreTrimsWhatItDecryptsWhileTheToolKeepsEveryByte(): void
    {
        $plaintext = " \t value with surrounding whitespace \n";
        $ciphertext = $this->encryptWithTool($plaintext, $this->ring);

        $results = $this->runStore($this->ring->export(), [['op' => 'decrypt', 'value' => $ciphertext->toString()]]);

        self::assertSame(trim($plaintext), $this->decodedPlaintext($results[0]));
        self::assertSame($plaintext, $this->services->cipher()->decrypt($ciphertext, $this->ring->active($this->services->keys()))?->bytes());
    }

    public function testTheStoreEncryptsUnderTheIndexTheToolAppended(): void
    {
        $old = $this->encryptWithTool('value under the old key', $this->ring);
        $newKey = $this->services->keyGenerator()->generate();
        $rotated = $this->ring->appended($newKey, $this->services->slots(), $this->services->rings());
        $underNewKey = $this->encryptWithTool('value under the new key', $rotated);

        $results = $this->runStore($rotated->export(), [
            ['op' => 'keyVersion'],
            ['op' => 'exportKeys'],
            ['op' => 'encrypt', 'plaintext' => base64_encode('written by the store after the rotation')],
            ['op' => 'decrypt', 'value' => $old->toString()],
            ['op' => 'decrypt', 'value' => $underNewKey->toString()],
        ]);

        self::assertSame(2, $results[0]['keyVersion'] ?? null);
        self::assertSame($rotated->export(), $this->stringResult($results[1], 'keys'));
        $written = $this->services->ciphertextParser()->parse($this->stringResult($results[2], 'ciphertext'));
        self::assertNotNull($written);
        self::assertSame(2, $written->keyIndex());
        self::assertSame('written by the store after the rotation', $this->services->cipher()->decrypt($written, $newKey)?->bytes());
        self::assertSame('value under the old key', $this->decodedPlaintext($results[3]));
        self::assertSame('value under the new key', $this->decodedPlaintext($results[4]));
        self::assertSame(2, $underNewKey->keyIndex());
    }

    public function testTheStoreReadsAValueUnderARetiredSlotAsEmpty(): void
    {
        $old = $this->encryptWithTool('value left on the old key', $this->ring);
        $rotated = $this->ring->appended($this->services->keyGenerator()->generate(), $this->services->slots(), $this->services->rings());
        $retired = $rotated->withRetired([1], [$this->services->keyGenerator()->placeholder()], $this->services->slots(), $this->services->rings());

        $beforeRetire = $this->runStore($rotated->export(), [['op' => 'decrypt', 'value' => $old->toString()]]);
        $afterRetire = $this->runStore($retired->export(), [
            ['op' => 'decrypt', 'value' => $old->toString()],
            ['op' => 'keyVersion'],
        ]);

        self::assertSame('value left on the old key', $this->decodedPlaintext($beforeRetire[0]));
        self::assertSame('', $this->decodedPlaintext($afterRetire[0]));
        self::assertSame(2, $afterRetire[1]['keyVersion'] ?? null);
    }

    public function testTheStoreDecodesABase64KeyAndARawKeyAsTheToolDoes(): void
    {
        $raw = KeyMaterial::rawKey();
        $encoded = new Key('base64' . base64_encode($raw));
        $ring = $this->services->ringParser()->parse($raw);
        $rotated = $ring->appended($this->services->keyGenerator()->generate(), $this->services->slots(), $this->services->rings());
        $underRaw = $this->encryptWithTool('same key bytes', $ring);

        $results = $this->runStore($rotated->export() . "\n" . $encoded->raw(), [
            ['op' => 'decrypt', 'value' => $underRaw->toString()],
            ['op' => 'decrypt', 'value' => '2:3:' . $underRaw->payload()],
        ]);

        self::assertSame('same key bytes', $this->decodedPlaintext($results[0]));
        self::assertSame('same key bytes', $this->decodedPlaintext($results[1]));
    }

    /**
     * @return list<string>
     */
    private function plaintextsWithoutSurroundingWhitespace(): array
    {
        return [
            'api-secret-' . bin2hex(random_bytes(8)),
            'Пароль — 密码 — كلمة السر — 🔑',
            '{"client_id":"abc","secret":"' . base64_encode(random_bytes(24)) . '"}',
            "inner\nnewline and\ttab",
            str_repeat('0123456789abcdef', 256),
        ];
    }

    private function encryptWithTool(string $plaintext, KeyRing $ring): Ciphertext
    {
        return $this->services->cipher()->encrypt(
            $this->services->plaintexts()->create($plaintext),
            $ring->activeIndex(),
            $ring->active($this->services->keys()),
        );
    }

    /**
     * @param list<array<string, string>> $operations
     *
     * @return list<array<array-key, mixed>>
     */
    private function runStore(string $ring, array $operations): array
    {
        $root = getenv('MAGENTO_ROOT');
        if (!is_string($root) || $root === '') {
            self::fail('MAGENTO_ROOT is not set: point it at an installed store code base to run the compatibility suite.');
        }
        $php = getenv('MAGENTO_PHP');
        $php = is_string($php) && $php !== '' ? $php : 'php';

        $process = new Process(
            [$php, '-d', 'display_errors=stderr', self::SCRIPT],
            null,
            ['MAGENTO_ROOT' => $root],
            json_encode(['ring' => $ring, 'operations' => $operations], JSON_THROW_ON_ERROR),
            120,
        );
        $process->run();

        if (!$process->isSuccessful()) {
            self::fail(sprintf(
                "The store's Encryptor could not run with MAGENTO_PHP \"%s\" on %s (exit code %s). The PHP must satisfy %s/vendor/composer/platform_check.php.\n%s",
                $php,
                $root,
                var_export($process->getExitCode(), true),
                $root,
                trim($process->getErrorOutput()),
            ));
        }

        $output = json_decode($process->getOutput(), true);
        if (!is_array($output) || !is_array($output['results'] ?? null) || !array_is_list($output['results'])) {
            self::fail('The store script answered no result list: ' . $process->getOutput());
        }
        $results = [];
        foreach ($output['results'] as $result) {
            self::assertIsArray($result);
            $results[] = $result;
        }
        self::assertCount(count($operations), $results);

        return $results;
    }

    /**
     * @param array<array-key, mixed> $result
     */
    private function stringResult(array $result, string $field): string
    {
        $value = $result[$field] ?? null;
        self::assertIsString($value, sprintf('The store answered no "%s".', $field));

        return $value;
    }

    /**
     * @param array<array-key, mixed> $result
     */
    private function decodedPlaintext(array $result): string
    {
        $bytes = base64_decode($this->stringResult($result, 'plaintext'), true);
        self::assertIsString($bytes, 'The store answered a plaintext that is not base64.');

        return $bytes;
    }
}
