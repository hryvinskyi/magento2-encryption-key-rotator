<?php

declare(strict_types=1);

namespace Hryvinskyi\EncryptionKeyRotator\DependencyInjection\Factory;

/**
 * Renders the PHP source of the class that implements one factory interface.
 *
 * The generated class receives, through its constructor, every constructor parameter of the created
 * class that some creation method does not take: same name, type, default and wiring attributes, so the
 * container wires it exactly as it would wire the created class. Each creation method passes its own
 * arguments and those stored values by name to `new Target(...)` and returns the result; it does
 * nothing else.
 *
 * The class is named after the SHA-1 of its source (rendered with a neutral placeholder for the name),
 * so identical factories always produce the same file and a changed factory always produces a new one.
 */
final class FactorySourceGenerator
{
    public const NAMESPACE = 'Hryvinskyi\\EncryptionKeyRotator\\Generated\\Factory';

    private const CLASS_PLACEHOLDER = '__GENERATED_FACTORY__';

    public function __construct(
        private readonly FactoryAnatomy $anatomy,
        private readonly PhpCodeRenderer $code,
    ) {}

    /**
     * @param \ReflectionClass<object> $interface
     * @param \ReflectionClass<object> $target
     *
     * @return array{class: string, shortName: string, source: string}
     */
    public function generate(\ReflectionClass $interface, \ReflectionClass $target): array
    {
        $template = $this->render($interface, $target);
        $shortName = 'Factory_' . sha1($template);

        return [
            'class' => self::NAMESPACE . '\\' . $shortName,
            'shortName' => $shortName,
            'source' => str_replace(self::CLASS_PLACEHOLDER, $shortName, $template),
        ];
    }

    /**
     * @param \ReflectionClass<object> $interface
     * @param \ReflectionClass<object> $target
     */
    private function render(\ReflectionClass $interface, \ReflectionClass $target): string
    {
        $mirrored = $this->anatomy->mirroredParameters($interface, $target);
        $body = [];
        if ($mirrored !== []) {
            $body[] = $this->renderProperties($mirrored, $target);
            $body[] = $this->renderConstructor($mirrored, $target);
        }
        foreach ($this->anatomy->creationMethods($interface) as $method) {
            $body[] = $this->renderMethod($method, $interface, $target);
        }

        // The declaration is conditional: a class named by the hash of its source may already be declared in
        // this process from another build directory, and loading this copy must then be a no-op.
        return "<?php\n\n"
            . "declare(strict_types=1);\n\n"
            . 'namespace ' . self::NAMESPACE . ";\n\n"
            . "if (!\\class_exists(__NAMESPACE__ . '\\\\" . self::CLASS_PLACEHOLDER . "', false)) {\n"
            . "/**\n"
            . ' * Generated by the container build from \\' . $interface->getName() . "; never edited by hand.\n"
            . " */\n"
            . 'final class ' . self::CLASS_PLACEHOLDER . ' implements \\' . $interface->getName() . "\n"
            . "{\n"
            . implode("\n", $body)
            . "}\n"
            . "}\n";
    }

    /**
     * @param list<\ReflectionParameter> $mirrored
     * @param \ReflectionClass<object>   $target
     */
    private function renderProperties(array $mirrored, \ReflectionClass $target): string
    {
        $lines = '';
        foreach ($mirrored as $parameter) {
            $type = $this->code->type($parameter->getType(), $target);
            $lines .= sprintf("    private readonly %s $%s;\n", $type === '' ? 'mixed' : $type, $parameter->getName());
        }

        return $lines;
    }

    /**
     * @param list<\ReflectionParameter> $mirrored
     * @param \ReflectionClass<object>   $target
     */
    private function renderConstructor(array $mirrored, \ReflectionClass $target): string
    {
        $parameters = [];
        $assignments = [];
        foreach ($mirrored as $parameter) {
            $parameters[] = '        ' . $this->renderParameter($parameter, $target) . ',';
            $assignments[] = sprintf('        $this->%1$s = $%1$s;', $parameter->getName());
        }

        return "    public function __construct(\n"
            . implode("\n", $parameters) . "\n"
            . "    ) {\n"
            . implode("\n", $assignments) . "\n"
            . "    }\n";
    }

    /**
     * @param \ReflectionClass<object> $interface
     * @param \ReflectionClass<object> $target
     */
    private function renderMethod(\ReflectionMethod $method, \ReflectionClass $interface, \ReflectionClass $target): string
    {
        $parameters = [];
        foreach ($method->getParameters() as $parameter) {
            $parameters[] = $this->renderParameter($parameter, $interface);
        }

        $arguments = [];
        foreach ($this->anatomy->constructorParameters($target) as $parameter) {
            $name = $parameter->getName();
            $arguments[] = sprintf(
                $this->anatomy->takes($method, $name) ? '%1$s: $%1$s' : '%1$s: $this->%1$s',
                $name,
            );
        }

        return sprintf(
            "    public function %s(%s): %s\n    {\n        return new \\%s(%s);\n    }\n",
            $method->getName(),
            implode(', ', $parameters),
            $this->code->type($method->getReturnType(), $interface),
            $target->getName(),
            implode(', ', $arguments),
        );
    }

    /**
     * @param \ReflectionClass<object> $context the class that declares the parameter
     */
    private function renderParameter(\ReflectionParameter $parameter, \ReflectionClass $context): string
    {
        $type = $this->code->type($parameter->getType(), $context);

        return $this->code->attributes($parameter)
            . ($type === '' ? '' : $type . ' ')
            . '$' . $parameter->getName()
            . $this->code->defaultSuffix($parameter);
    }
}
